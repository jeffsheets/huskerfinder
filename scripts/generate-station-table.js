#!/usr/bin/env node
/**
 * Pre-renders the full station table into stations.html so search engines and
 * AI crawlers (which don't execute JavaScript) can see every station.
 *
 * Run after any change to js/stations.js:
 *   node scripts/generate-station-table.js
 *
 * The generated markup must stay in sync with renderStationTable() in
 * stations.html — it produces the identical all-filters-on table, which the
 * inline script only re-renders when a filter checkbox changes.
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const stationsSrc = fs.readFileSync(path.join(rootDir, 'js', 'stations.js'), 'utf8');
const stations = JSON.parse(stationsSrc.replace(/^const stations = /, '').replace(/;\s*$/, ''));

// Group stations by city + frequency to combine sports (mirrors stations.html)
const groupedStations = new Map();
stations.forEach(station => {
  const key = `${station.City}-${station.CallSign}-${station.Frequency}${station.Format}`;
  if (!groupedStations.has(key)) {
    groupedStations.set(key, { ...station, sports: [] });
  }
  groupedStations.get(key).sports.push(station.Sport);
});

// Nebraska first, Kansas last — keep in sync with renderStationTable() in stations.html
const stateOrder = { 'NE': 0, 'SD': 1, 'KS': 3 };
const stateRank = (s) => stateOrder[s] !== undefined ? stateOrder[s] : 2;
const sortedStations = Array.from(groupedStations.values()).sort((a, b) => {
  if (a.State !== b.State) {
    if (stateRank(a.State) !== stateRank(b.State)) return stateRank(a.State) - stateRank(b.State);
    return (a.State || '').localeCompare(b.State || '');
  }
  if (a.City !== b.City) return a.City.localeCompare(b.City);
  return a.Frequency - b.Frequency;
});

let html = `
    <table class="station-table">
      <thead>
        <tr>
          <th>City</th>
          <th>State</th>
          <th>Frequency</th>
          <th>Call Sign</th>
          <th>Sports</th>
        </tr>
      </thead>
      <tbody>
  `;

sortedStations.forEach(station => {
  const uniqueSports = [...new Set(station.sports)];
  const sportsHtml = uniqueSports.map(sport => {
    const sportClass = sport.toLowerCase().replace(/['\s]/g, '-');
    const shortLabel = {
      'Football': 'FB',
      'Volleyball': 'VB',
      "Men's Basketball": 'MBB',
      "Women's Basketball": 'WBB'
    }[sport] || sport;
    return `<span class="station-sport ${sportClass}">${shortLabel}</span>`;
  }).join(' ');

  html += `
      <tr>
        <td data-label="City:">${station.City}</td>
        <td data-label="State:">${station.State || ''}</td>
        <td data-label="Frequency:">${station.Frequency}${station.Format}</td>
        <td data-label="Call Sign:">${station.CallSign}${station.role ? ` <span class="station-role ${station.role}">${station.role}</span>` : ''}</td>
        <td data-label="Sports:">${sportsHtml}</td>
      </tr>
    `;
});

html += `
      </tbody>
    </table>
    <div class="station-count">
      Showing ${sortedStations.length} stations
    </div>
  `;

const startMarker = '<!-- STATIC-STATIONS-START (generated by scripts/generate-station-table.js — do not edit by hand) -->';
const endMarker = '<!-- STATIC-STATIONS-END -->';

const pagePath = path.join(rootDir, 'stations.html');
const page = fs.readFileSync(pagePath, 'utf8');
const startIdx = page.indexOf(startMarker);
const endIdx = page.indexOf(endMarker);
if (startIdx === -1 || endIdx === -1) {
  console.error('Markers not found in stations.html — expected STATIC-STATIONS-START/END comments inside #stationTable');
  process.exit(1);
}

const updated = page.slice(0, startIdx + startMarker.length) + '\n' + html.trim() + '\n  ' + page.slice(endIdx);
fs.writeFileSync(pagePath, updated);
console.log(`Rendered ${sortedStations.length} station rows into stations.html`);
